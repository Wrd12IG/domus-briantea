function dbApplyLang(lang) {
  const t = DB_TRANSLATIONS[lang] || DB_TRANSLATIONS.it;
  DB_MAP.forEach(({s, k, a}) => {
    document.querySelectorAll(s).forEach(el => {
      if (!t[k]) return;
      if (a === 'html') el.innerHTML = t[k];
      else if (a === 'placeholder') el.placeholder = t[k];
      else el.textContent = t[k];
    });
  });
  // night price spans
  document.querySelectorAll('.apt-price span').forEach(el => {
    if (t['apts.night']) el.textContent = t['apts.night'];
  });
  // html lang + active button
  document.documentElement.lang = lang;
  document.querySelectorAll('.nav-lang .lang-btn, .hero-lang .lang-btn').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === lang);
  });
  localStorage.setItem('db_lang', lang);
}

function setLang(lang) { dbApplyLang(lang); }

document.addEventListener('DOMContentLoaded', function() {
  const saved = localStorage.getItem('db_lang') || 'it';
  dbApplyLang(saved);
});
